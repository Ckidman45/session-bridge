$results = @()
function Check($name, $ok, $detail) {
    $script:results += @{ name = $name; ok = [bool]$ok }
    $mark = if ($ok) { 'PASS' } else { 'FAIL' }
    Write-Output ("{0}  {1}  {2}" -f $mark, $name, $detail)
}
function PostRaw($fileName, $raw) {
    $p = Join-Path (Join-Path $bridge 'inbox') $fileName
    [IO.File]::WriteAllText($p, $raw, $utf8)
    (Get-Item $p).LastWriteTime = (Get-Date).AddSeconds(-10)
}
function PostJob($job) { PostRaw (($job.id) + '.json') ($job | ConvertTo-Json -Depth 4) }
function RunRunner { & $pwshExe -NoProfile -File (Join-Path $bridge 'sessionbridge.ps1') | Out-Null }
function GetStatus($id) {
    $p = Join-Path (Join-Path $bridge 'outbox') "$id.status.json"
    if (Test-Path $p) { return ([IO.File]::ReadAllText($p, $utf8) | ConvertFrom-Json) }
    return $null
}
function FakeCalls {
    if (Test-Path $env:FAKECLI_LOG) {
        return @([IO.File]::ReadAllLines($env:FAKECLI_LOG) | ForEach-Object { $_ | ConvertFrom-Json } | Where-Object { $_.phase -eq 'invoked' })
    }
    return @()
}

