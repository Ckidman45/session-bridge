# run-tests.ps1 - SessionBridge guard tests. Runs the real runner against a
# fake CLI (tests/fake-cli.ps1): no real AI CLI and no scheduled task involved.
# Requires PowerShell 5.1+ or PowerShell 7+ on any OS.
#
#   pwsh -NoProfile -File tests/run-tests.ps1        (or powershell on Windows)
#
# Every test asserts a PASS/FAIL line; the script exits 1 if any test fails.
# The guards are tested as guards: each one is given an input that must make
# it fire (rejection, timeout, interruption), not just a happy path.

