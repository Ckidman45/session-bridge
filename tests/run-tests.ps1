# Record the integrity manifest exactly as install.ps1 does (runner + config
# + every adapter), so the runner's manifest verification is exercised.
function Write-Manifest {
    $rels = @('sessionbridge.ps1', 'sessionbridge.config.json') + @(
        Get-ChildItem (Join-Path $bridge 'adapters') -Filter *.json | Sort-Object Name | ForEach-Object { 'adapters/' + $_.Name })
    $lines = foreach ($rel in $rels) {
        $full = Join-Path $bridge ($rel -replace '/', [IO.Path]::DirectorySeparatorChar)
        "{0}  {1}" -f $rel, (Get-FileHash $full -Algorithm SHA256).Hash
    }
    [IO.File]::WriteAllText((Join-Path $bridge 'sessionbridge.expected.sha256'), ($lines -join "`n") + "`n", $utf8)
}
Write-Manifest

$env:FAKECLI_LOG = Join-Path $work 'fake-log.jsonl'
